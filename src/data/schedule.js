// The daily order of the Mikdash — data for the "happening now" list, the info panel and the sim (ARCHITECTURE.md §9).
//
// AUTHORITY: Mishnah Tamid ch. 1–7 gives the ORDER of the day; Yoma ch. 1–3 (+ Bavli 14b–15a, 20b–28b, 33a, 37a–b,
// 39a–b, 44a), Middot 1–2 and 5, Shekalim 4–5, Rambam Beit HaBechirah 8 and the report (Part VIII §27–§36, IX, XII,
// XIII, XIV; ../report/parts) give the rest. Clock minutes are almost never given by the sources: every time is a
// zman-relative spec, and `timing.confidence` says what is sourced —
//   'explicit'       the hour itself is in the source (Pesachim 5:1's 8½ / 9½ hours; the nivreshet "when the sun rises")
//   'ordering'       the sequence is sourced, the minutes are reconstruction
//   'reconstruction' neither the hour nor its place in a sequence is given (chamber work, occasional scenes)
// Disagreements are stated in the description and the opinion shown is named (the report's locks, Part XI).
//
// TIME SPECS (resolved by ctx.time.resolve, §6): { at: 'alot'|'sunrise'|'sunset'|'tzeit'|…, offset: minutes } |
// { dayHour: h } (GRA seasonal hours from sunrise) | { nightHour: h } (from sunset). The pre-dawn chain is anchored on
// alot (dawn, sun −16.1°) and the gate-opening/slaughter chain on sunrise, as the report's clock (§28) does; the
// chain was checked to keep its order across the year (docs/decisions/schedule-data.md, "Validation").
// Night events wrap past midnight (end < start on the clock): the clock wraps on one civil date (§6).
//
// DAY TYPES: every event lists its dayTypes explicitly (ctx.time.dayType is 'weekday' | 'friday' | 'shabbat' by the
// civil date, so a 'shabbat' day's small hours are Shabbat night and a 'friday' evening is Shabbat eve).
// 'occasional' marks reference-only events that belong to no ordinary day (e.g. the yearly compounding of the
// incense): they never match ctx.time.dayType, so they stay off the daily clock but remain available to info panels.
//
// POSITIONS (site amot, X east / Y north / Z up): `pos` is where the action is; `view.at` is a walkable standing spot
// [X, Y, Z] — Z is the floor level, which the player uses to pick the level (player/goto.js accepts [X,Y(,Z)]).
//
// OFFERINGS (optional key): `offerings: [typeId, …]` lists the individual offerings an event stages — ids of
// OFFERING_TYPES in src/data/offerings.js, which holds each type's steps (actors, stations, props, minutes, sources),
// the day and night rules, the Cheshvan-weekday frequencies and offeringWindows(dayType, zmanim, opts).
// COVERAGE: node tools/coverage.mjs checks that something watchable is going on in every minute of every day type.
//
// CHOREOGRAPHY MODULES (src/sim/choreo/<id>.js) — what each must stage:
//   locking-up        the kohen at the keys slab of Beit HaMoked: lifts it, takes the keys, locks from within, a Levi lies
//                     down outside the door, keys returned, garment spread on the slab, he sleeps on it.
